CREATE TABLE IF NOT EXISTS states (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  sigla CHAR(2) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS cities (
  id UUID PRIMARY KEY,
  nome_cidade VARCHAR(255) NOT NULL,
  url_imagem TEXT,
  descricao TEXT,
  latitude DOUBLE PRECISION CHECK (latitude BETWEEN -90 AND 90),
  longitude DOUBLE PRECISION CHECK (longitude BETWEEN -180 AND 180),
  estado_id INTEGER NOT NULL REFERENCES states(id) ON DELETE RESTRICT,
  criado_por UUID,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_cities_nome ON cities (nome_cidade);
CREATE INDEX IF NOT EXISTS idx_cities_estado ON cities (estado_id);

CREATE TABLE IF NOT EXISTS tourist_points (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cidade_id UUID NOT NULL REFERENCES cities(id) ON DELETE CASCADE,
  titulo VARCHAR(255) NOT NULL,
  descricao TEXT,
  url_imagem TEXT
);
CREATE INDEX IF NOT EXISTS idx_tourist_points_city ON tourist_points(cidade_id);

CREATE TABLE IF NOT EXISTS travel_options (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cidade_id UUID NOT NULL REFERENCES cities(id) ON DELETE CASCADE,
  tipo VARCHAR(50) NOT NULL DEFAULT 'Terrestre',
  titulo VARCHAR(255) NOT NULL,
  descricao TEXT
);
CREATE INDEX IF NOT EXISTS idx_travel_options_city ON travel_options(cidade_id);

CREATE TABLE IF NOT EXISTS activities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cidade_id UUID NOT NULL REFERENCES cities(id) ON DELETE CASCADE,
  titulo VARCHAR(255) NOT NULL,
  descricao TEXT,
  url_imagem TEXT
);
CREATE INDEX IF NOT EXISTS idx_activities_city ON activities(cidade_id);

CREATE TABLE IF NOT EXISTS tips (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cidade_id UUID NOT NULL REFERENCES cities(id) ON DELETE CASCADE,
  titulo VARCHAR(255) NOT NULL,
  descricao TEXT,
  url_imagem TEXT
);
CREATE INDEX IF NOT EXISTS idx_tips_city ON tips(cidade_id);

CREATE TABLE IF NOT EXISTS comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL,
  cidade_id UUID NOT NULL REFERENCES cities(id) ON DELETE CASCADE,
  mensagem TEXT NOT NULL CHECK (length(trim(mensagem)) > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_comments_city_created ON comments(cidade_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_comments_user ON comments(user_id);

CREATE TABLE IF NOT EXISTS favorites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL,
  cidade_id UUID NOT NULL REFERENCES cities(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_favorites_user_city UNIQUE(user_id, cidade_id)
);
CREATE INDEX IF NOT EXISTS idx_favorites_city ON favorites(cidade_id);

CREATE TABLE IF NOT EXISTS route_suggestions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL,
  estado VARCHAR(100) NOT NULL,
  nome_cidade VARCHAR(255) NOT NULL,
  latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  imagem_capa TEXT,
  descricao_cidade TEXT,
  como_chegar JSONB NOT NULL DEFAULT '[]',
  pontos_turisticos JSONB NOT NULL DEFAULT '[]',
  atividades JSONB NOT NULL DEFAULT '[]',
  dicas JSONB NOT NULL DEFAULT '[]',
  data_submissao TIMESTAMPTZ NOT NULL DEFAULT now(),
  status VARCHAR(20) NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente','aprovado','rejeitado')),
  obs_admin TEXT NOT NULL DEFAULT '',
  id_admin UUID,
  cidade_id UUID REFERENCES cities(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_route_suggestions_user ON route_suggestions(user_id);
CREATE INDEX IF NOT EXISTS idx_route_suggestions_status ON route_suggestions(status);

